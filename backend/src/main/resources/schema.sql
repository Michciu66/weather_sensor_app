CREATE TABLE IF NOT EXISTS admins (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        admin_username VARCHAR(255) NOT NULL UNIQUE,
                        admin_password VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS series (
                        series_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        series_min NUMERIC NOT NULL,
                        series_max NUMERIC NOT NULL,
                        series_name VARCHAR(100) NOT NULL,
                        series_color VARCHAR(7) NOT NULL,
                        series_icon VARCHAR(255),
                        series_unit VARCHAR(20),

                        CONSTRAINT chk_series_min_less_than_max
                            CHECK (series_min < series_max),

                        CONSTRAINT chk_series_color_format
                            CHECK (series_color ~ '^#[0-9A-Fa-f]{6}$')
    );

CREATE TABLE IF NOT EXISTS sensors (
                         sensor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         sensor_name VARCHAR(100) NOT NULL,
                         series_id BIGINT NOT NULL,
                         api_key_hash VARCHAR(255) NOT NULL UNIQUE,
                         created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                         last_measurement_at TIMESTAMP WITH TIME ZONE,

                         CONSTRAINT fk_sensor_series
                             FOREIGN KEY (series_id)
                                 REFERENCES series(series_id)
                                 ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS measurements (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              series_id BIGINT NOT NULL,
                              sensor_id BIGINT,
                              measurement_value NUMERIC NOT NULL,
                              measurement_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,

                              CONSTRAINT fk_measurement_series
                                  FOREIGN KEY (series_id)
                                      REFERENCES series(series_id)
                                      ON DELETE CASCADE,

                              CONSTRAINT fk_measurement_sensor
                                  FOREIGN KEY (sensor_id)
                                      REFERENCES sensors(sensor_id)
                                      ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS auth_tokens (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             admin_id BIGINT NOT NULL,
                             token_hash VARCHAR(255) NOT NULL UNIQUE,
                             expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                             revoked_at TIMESTAMP WITH TIME ZONE,

                             CONSTRAINT fk_auth_token_admin
                                 FOREIGN KEY (admin_id)
                                     REFERENCES admins(id)
                                     ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_measurement_timestamp
    ON measurements(measurement_timestamp);

CREATE INDEX IF NOT EXISTS idx_measurement_series_timestamp
    ON measurements(series_id, measurement_timestamp);

CREATE INDEX IF NOT EXISTS idx_sensors_apihashkey
    ON sensors(api_key_hash);